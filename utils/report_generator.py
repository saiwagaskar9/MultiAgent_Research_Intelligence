"""
Report generator — PDF and DOCX export using ReportLab and python-docx.
"""
import os
import logging
from datetime import datetime
from typing import Optional
from config.settings import OUTPUTS_DIR

logger = logging.getLogger(__name__)


# ─── PDF Generation ───────────────────────────────────────────────────────────
def generate_pdf(report_text: str, topic: str, session_id: str) -> str:
    """Generate a PDF report using ReportLab. Returns file path."""
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.lib import colors
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
        from reportlab.platypus import Table, TableStyle
        from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_JUSTIFY

        filename = f"report_{session_id[:8]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
        filepath = os.path.join(OUTPUTS_DIR, filename)

        doc = SimpleDocTemplate(
            filepath,
            pagesize=A4,
            rightMargin=2*cm, leftMargin=2*cm,
            topMargin=2*cm, bottomMargin=2*cm,
        )

        styles = getSampleStyleSheet()
        story = []

        # Title style
        title_style = ParagraphStyle(
            "CustomTitle",
            parent=styles["Heading1"],
            fontSize=20,
            textColor=colors.HexColor("#1a1a2e"),
            spaceAfter=6,
            alignment=TA_CENTER,
            fontName="Helvetica-Bold",
        )
        h2_style = ParagraphStyle(
            "H2",
            parent=styles["Heading2"],
            fontSize=14,
            textColor=colors.HexColor("#16213e"),
            spaceBefore=12,
            spaceAfter=4,
            fontName="Helvetica-Bold",
        )
        body_style = ParagraphStyle(
            "Body",
            parent=styles["Normal"],
            fontSize=10,
            leading=16,
            spaceAfter=6,
            alignment=TA_JUSTIFY,
        )
        meta_style = ParagraphStyle(
            "Meta",
            parent=styles["Normal"],
            fontSize=9,
            textColor=colors.grey,
            alignment=TA_CENTER,
            spaceAfter=4,
        )

        # Header
        story.append(Paragraph("Multi-Agent Research Intelligence Platform", title_style))
        story.append(Paragraph(f"Research Report: {topic}", h2_style))
        story.append(Paragraph(f"Generated: {datetime.now().strftime('%B %d, %Y %H:%M')}", meta_style))
        story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#0f3460")))
        story.append(Spacer(1, 0.4*cm))

        # Parse and render markdown-like content
        for line in report_text.split("\n"):
            line = line.strip()
            if not line:
                story.append(Spacer(1, 0.2*cm))
                continue
            if line.startswith("## "):
                story.append(Paragraph(line[3:], h2_style))
            elif line.startswith("# "):
                story.append(Paragraph(line[2:], title_style))
            elif line.startswith("### "):
                h3_style = ParagraphStyle("H3", parent=h2_style, fontSize=12, textColor=colors.HexColor("#0f3460"))
                story.append(Paragraph(line[4:], h3_style))
            elif line.startswith("- ") or line.startswith("* "):
                bullet_style = ParagraphStyle("Bullet", parent=body_style, leftIndent=20, bulletIndent=10)
                story.append(Paragraph(f"• {line[2:]}", bullet_style))
            elif line.startswith("**") and line.endswith("**"):
                bold_style = ParagraphStyle("Bold", parent=body_style, fontName="Helvetica-Bold")
                story.append(Paragraph(line[2:-2], bold_style))
            else:
                # Clean any remaining markdown
                clean = line.replace("**", "").replace("*", "").replace("`", "")
                story.append(Paragraph(clean, body_style))

        # Footer
        story.append(Spacer(1, 0.5*cm))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.grey))
        story.append(Paragraph(
            f"Generated by Multi-Agent Research Intelligence Platform v2.0 | Session: {session_id[:8]}",
            meta_style
        ))

        doc.build(story)
        return filepath

    except Exception as e:
        logger.error(f"PDF generation failed: {e}")
        raise


# ─── DOCX Generation ──────────────────────────────────────────────────────────
def generate_docx(report_text: str, topic: str, session_id: str) -> str:
    """Generate a DOCX report using python-docx. Returns file path."""
    try:
        from docx import Document
        from docx.shared import Inches, Pt, RGBColor
        from docx.enum.text import WD_ALIGN_PARAGRAPH

        filename = f"report_{session_id[:8]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.docx"
        filepath = os.path.join(OUTPUTS_DIR, filename)

        doc = Document()

        # Document settings
        section = doc.sections[0]
        section.page_width = Inches(8.5)
        section.page_height = Inches(11)

        # Title
        title = doc.add_heading("Multi-Agent Research Intelligence Platform", level=0)
        title.alignment = WD_ALIGN_PARAGRAPH.CENTER

        sub_title = doc.add_heading(f"Research Report: {topic}", level=1)
        sub_title.alignment = WD_ALIGN_PARAGRAPH.CENTER

        meta = doc.add_paragraph(f"Generated: {datetime.now().strftime('%B %d, %Y %H:%M')}")
        meta.alignment = WD_ALIGN_PARAGRAPH.CENTER

        doc.add_paragraph()  # spacer

        # Parse content
        for line in report_text.split("\n"):
            line_stripped = line.strip()
            if not line_stripped:
                doc.add_paragraph()
                continue
            if line_stripped.startswith("# "):
                doc.add_heading(line_stripped[2:], level=1)
            elif line_stripped.startswith("## "):
                doc.add_heading(line_stripped[3:], level=2)
            elif line_stripped.startswith("### "):
                doc.add_heading(line_stripped[4:], level=3)
            elif line_stripped.startswith("- ") or line_stripped.startswith("* "):
                p = doc.add_paragraph(line_stripped[2:], style="List Bullet")
            else:
                # Handle bold
                p = doc.add_paragraph()
                parts = line_stripped.split("**")
                for i, part in enumerate(parts):
                    run = p.add_run(part)
                    if i % 2 == 1:  # odd index = bold
                        run.bold = True

        # Footer
        doc.add_paragraph()
        footer_p = doc.add_paragraph(
            f"Generated by Multi-Agent Research Intelligence Platform v2.0 | Session: {session_id[:8]}"
        )
        footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER

        doc.save(filepath)
        return filepath

    except Exception as e:
        logger.error(f"DOCX generation failed: {e}")
        raise


# ─── Markdown Saving ──────────────────────────────────────────────────────────
def save_markdown(report_text: str, topic: str, session_id: str) -> str:
    """Save report as a Markdown file. Returns file path."""
    filename = f"report_{session_id[:8]}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
    filepath = os.path.join(OUTPUTS_DIR, filename)
    header = f"""# Research Report: {topic}

> Generated by Multi-Agent Research Intelligence Platform v2.0
> Date: {datetime.now().strftime('%B %d, %Y %H:%M')}
> Session: {session_id[:8]}

---

"""
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(header + report_text)
    return filepath

